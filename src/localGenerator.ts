import { createHash } from 'node:crypto';
import * as path from 'node:path';
import { MethodDeclaration, Node, Project, Statement, SyntaxKind, VariableDeclarationKind } from 'ts-morph';
import { defaultDirectories, GeneratedFile, GenerationResult, RepoContext } from './types';
import { alignTestSteps, parseTestSteps } from './testSteps';
import { pageGroupSlug } from './pageGrouping';

export interface NamingAction { action: string; label: string; target?: string }
export interface LocalResult { result?: GenerationResult; reason: string; namingNotice?: string; namingActions?: NamingAction[] }
const marker = '// Generated by POM Agent local rules v1.';
const baseSource = `${marker}\nimport type { Page } from '@playwright/test';\nexport class BasePage {\n  constructor(protected readonly page: Page) {}\n}\n`;
const hash = (text: string): string => createHash('sha256').update(text).digest('hex').slice(0, 10);
const pascal = (text: string): string => text.split(/[^a-zA-Z0-9]+/).filter(Boolean).map(word => word[0].toUpperCase() + word.slice(1)).join('');
const camel = (text: string): string => { const name = pascal(text) || 'Element'; return /^[0-9]/.test(name) ? `element${name}` : name[0].toLowerCase() + name.slice(1); };
const importPath = (from: string, to: string): string => {
  const relative = path.posix.relative(path.posix.dirname(from), to).replace(/\.ts$/, '');
  return relative.startsWith('.') ? relative : `./${relative}`;
};

// Compare syntax tokens, preserving literal values while ignoring layout changes.
const codeTokens = (node: Node | undefined): string => JSON.stringify(node?.getDescendants()
    .filter(child => child.getChildCount() === 0)
    .map(child => [child.getKind(), child.getText()]));
function sameCode(left: Node | undefined, right: Node | undefined): boolean {
  return codeTokens(left) === codeTokens(right);
}

const methodMeaning = (method: MethodDeclaration): string => JSON.stringify([
  method.getParameters().map(codeTokens), codeTokens(method.getBody()), method.getReturnTypeNode()?.getText(),
  method.getModifiers().map(item => item.getText()),
]);

function literal(node: Node | undefined): string | undefined {
  return node && (Node.isStringLiteral(node) || Node.isNoSubstitutionTemplateLiteral(node)) ? node.getLiteralText() : undefined;
}

interface LocatorChain { expression: string; label: string; suffix: string; type: 'page' | 'locator' | 'frame'; css: boolean; frame?: string }
function locator(call: Node): LocatorChain | undefined {
  if (Node.isPropertyAccessExpression(call) && call.getExpression().getKind() === SyntaxKind.ThisKeyword && call.getName() === 'page') return { expression: 'page', label: 'Page', suffix: 'Element', type: 'page', css: false };
  if (Node.isIdentifier(call) && call.getText() === 'page') return { expression: 'page', label: 'Page', suffix: 'Element', type: 'page', css: false };
  if (!Node.isCallExpression(call)) return undefined;
  const access = call.getExpression();
  if (!Node.isPropertyAccessExpression(access)) return undefined;
  const parent = locator(access.getExpression());
  if (!parent) return undefined;
  const kind = access.getName();
  const args = call.getArguments();
  if (kind === 'frameLocator' && args.length === 0 && parent.type === 'page') {
    const expression = `${parent.expression}.frameLocator()`;
    return { expression, label: 'Frame', suffix: 'Element', type: 'frame', css: parent.css, frame: expression };
  }
  if (kind === 'contentFrame') return parent.type === 'locator' && args.length === 0
    ? { ...parent, expression: `${parent.expression}.contentFrame()`, type: 'frame', frame: `${parent.expression}.contentFrame()` } : undefined;
  if (['first', 'last', 'nth'].includes(kind)) {
    if (parent.type !== 'locator') return undefined;
    if (kind === 'nth') {
      if (args.length !== 1 || !Node.isNumericLiteral(args[0]) || !Number.isSafeInteger(args[0].getLiteralValue()) || args[0].getLiteralValue() < 0) return undefined;
    } else if (args.length) return undefined;
    return { ...parent, expression: `${parent.expression}.${kind}(${kind === 'nth' ? args[0].getText() : ''})` };
  }
  const first = literal(args[0]);
  if (kind === 'locator' || kind === 'frameLocator') {
    if (first === undefined || args.length !== 1) return undefined;
    const expression = `${parent.expression}.${kind}(${JSON.stringify(first)})`;
    return { expression, label: kind === 'locator' ? 'RecordedElement' : 'Frame', suffix: 'Element', type: kind === 'locator' ? 'locator' : 'frame', css: true,
      frame: kind === 'frameLocator' ? expression : parent.type === 'frame' ? parent.expression : parent.frame };
  }
  if (!['getByRole', 'getByTestId', 'getByLabel', 'getByPlaceholder', 'getByText'].includes(kind)) return undefined;
  if (first === undefined || args.length > 2 || args.length < 1) return undefined;
  let label = first || parent.label;
  const options: Record<string, string | boolean> = {};
  if (args[1]) {
    if (kind === 'getByTestId' || !Node.isObjectLiteralExpression(args[1])) return undefined;
    for (const prop of args[1].getProperties()) {
      if (!Node.isPropertyAssignment(prop)) return undefined;
      const name = literal(prop.getNameNode()) ?? prop.getName();
      if (!['name', 'description', 'exact'].includes(name) || (name !== 'exact' && kind !== 'getByRole')) return undefined;
      const value = prop.getInitializer();
      if (name === 'name' || name === 'description') { const text = literal(value); if (text === undefined) return undefined; options[name] = text; }
      else {
        if (value?.getKind() !== SyntaxKind.TrueKeyword && value?.getKind() !== SyntaxKind.FalseKeyword) return undefined;
        options.exact = value.getKind() === SyntaxKind.TrueKeyword;
      }
    }
  }
  // Accessible description is a separate filter; preserve it and only use it as
  // a naming fallback when no accessible name was recorded.
  label = typeof options.name === 'string' ? options.name : typeof options.description === 'string' ? options.description : label;
  const suffix = kind === 'getByRole' ? ({ button: 'Btn', link: 'Link', checkbox: 'Checkbox', combobox: 'Dropdown', textbox: 'Input' }[first] ?? 'Element')
    : ['getByLabel', 'getByPlaceholder'].includes(kind) ? 'Input' : 'Element';
  return { expression: `${parent.expression}.${kind}(${JSON.stringify(first)}${args[1] ? `, ${JSON.stringify(options)}` : ''})`, label, suffix, type: 'locator', css: parent.css,
    frame: parent.type === 'frame' ? parent.expression : parent.frame };
}

/** Recognize only the adjacent wait -> goto -> await pattern with an unused popup handle.
 * The generated page method preserves registration/navigation/wait ordering exactly. */
function popupNavigations(statements: Statement[]): { statements: Statement[]; navigations: Set<Statement> } {
  const result: Statement[] = [];
  const navigations = new Set<Statement>();
  const identifiers = statements.flatMap(statement => statement.getDescendantsOfKind(SyntaxKind.Identifier)).map(node => node.getText());
  for (let i = 0; i < statements.length; i++) {
    const start = statements[i], navigation = statements[i + 1], finish = statements[i + 2];
    if (Node.isVariableStatement(start) && start.getDeclarationKind() === VariableDeclarationKind.Const && start.getDeclarations().length === 1
      && navigation && Node.isExpressionStatement(navigation) && finish && Node.isVariableStatement(finish)
      && finish.getDeclarationKind() === VariableDeclarationKind.Const && finish.getDeclarations().length === 1) {
      const pending = start.getDeclarations()[0], completed = finish.getDeclarations()[0];
      const wait = pending.getInitializer(), nav = navigation.getExpression(), done = completed.getInitializer();
      if (Node.isIdentifier(pending.getNameNode()) && Node.isIdentifier(completed.getNameNode())
        && wait && Node.isCallExpression(wait) && wait.getExpression().getText() === 'page.waitForEvent'
        && wait.getArguments().length === 1 && literal(wait.getArguments()[0]) === 'popup'
        && Node.isAwaitExpression(nav) && Node.isCallExpression(nav.getExpression())
        && nav.getExpression().asKindOrThrow(SyntaxKind.CallExpression).getExpression().getText() === 'page.goto'
        && done && Node.isAwaitExpression(done) && done.getExpression().getText() === pending.getName()
        && identifiers.filter(name => name === pending.getName()).length === 2
        && identifiers.filter(name => name === completed.getName()).length === 1) {
        result.push(navigation); navigations.add(navigation); i += 2; continue;
      }
    }
    result.push(start);
  }
  return { statements: result, navigations };
}

interface Section {
  slug: string; className: string; instance: string;
  locators: Map<string, { expression: string; name: string; css: boolean; frame?: string }>;
  methods: Map<string, string>;
  existingLocators: Map<string, string>;
  methodIdentities: Map<string, string>;
}

function locatorFieldName(label: string, suffix: string): string {
  let words = label.replace(/([a-z0-9])([A-Z])/g, '$1_$2').replace(/[^a-zA-Z0-9]+/g, '_').replace(/^_+|_+$/g, '').toUpperCase() || 'ELEMENT';
  if (suffix === 'Input' && /^(LOGIN|USER_NAME|USERNAME)$/.test(words)) words = 'USERNAME';
  const ending = ({ Input: 'FIELD', Btn: 'BUTTON', Link: 'LINK', Dropdown: 'DROPDOWN', Checkbox: 'CHECKBOX' } as Record<string, string>)[suffix] ?? 'ELEMENT';
  if (/^[0-9]/.test(words)) words = `ELEMENT_${words}`;
  return `${words.slice(0, 64)}_${ending}`;
}

function existingLocatorNames(project: Project, ctx: RepoContext, filePath: string): Map<string, string> {
  const names = new Map<string, string>();
  const file = ctx.existingPages.find(item => item.relativePath === filePath);
  if (!file) return names;
  const klass = project.createSourceFile(`/names/${filePath}`, file.content, { overwrite: true }).getClasses()[0];
  let resolvedFile = 0;
  for (const property of klass?.getProperties() ?? []) {
    const initializer = property.getInitializer();
    let expression = initializer ? locator(initializer)?.expression : undefined;
    // New generated locator fields may start with a reusable frame field. Expand
    // earlier fields locally so repeat generation still recognizes the complete
    // recorded chain and does not duplicate locators.
    if (!expression && initializer) {
      const text = initializer.getText().replace(/\bthis\.([A-Za-z_$][\w$]*)/g, (match, name: string) => names.get(name) ?? match);
      const resolved = project.createSourceFile(`/names-resolved/${filePath}-${resolvedFile++}.ts`, `${text};`, { overwrite: true });
      const statement = resolved.getStatements()[0];
      expression = Node.isExpressionStatement(statement) ? locator(statement.getExpression())?.expression : undefined;
    }
    names.set(property.getName(), expression ?? 'reserved');
  }
  for (const assignment of klass?.getConstructors()[0]?.getDescendantsOfKind(SyntaxKind.BinaryExpression) ?? []) {
    const left = assignment.getLeft();
    if (assignment.getOperatorToken().getKind() !== SyntaxKind.EqualsToken || !Node.isPropertyAccessExpression(left) || left.getExpression().getKind() !== SyntaxKind.ThisKeyword) continue;
    const expression = locator(assignment.getRight())?.expression;
    if (expression) names.set(left.getName(), expression);
  }
  return names;
}

/** Conservative AST rules: unsupported syntax declines the entire recording, never drops statements. */
export function generateLocally(codegenSource: string, ctx: RepoContext): LocalResult {
  if (ctx.conventions?.trim() && !ctx.namingPlan) return { reason: 'Repository conventions require interpretation.' };
  const hints = ctx.namingPlan ?? (ctx.testSteps?.trim() ? parseTestSteps(ctx.testSteps) : undefined);
  const namingActions: NamingAction[] = [];
  const project = new Project({ useInMemoryFileSystem: true });
  const source = project.createSourceFile('/recording.ts', codegenSource);
  if (project.getProgram().compilerObject.getSyntacticDiagnostics(source.compilerNode).length) return { reason: 'The selection is not a complete TypeScript statement sequence.' };
  let statements: Statement[] = [];
  let title = 'Recorded flow';
  let testCount = 0;
  for (const statement of source.getStatements()) {
    if (Node.isImportDeclaration(statement)) {
      if (statement.getModuleSpecifierValue() !== '@playwright/test' || statement.getDefaultImport() || statement.getNamespaceImport()
        || statement.getNamedImports().some(item => !['test', 'expect'].includes(item.getName()) || item.getAliasNode())) return { reason: 'Custom imports require repository-aware generation.' };
      continue;
    }
    const expression = Node.isExpressionStatement(statement) ? statement.getExpression() : undefined;
    if (expression && Node.isCallExpression(expression) && expression.getExpression().getText() === 'test') {
      const [name, callback] = expression.getArguments();
      const testTitle = literal(name);
      if (++testCount > 1 || statements.length || testTitle === undefined || expression.getArguments().length !== 2 || !callback || !Node.isArrowFunction(callback) || !callback.isAsync()) return { reason: 'Only one plain async test is supported locally.' };
      const parameters = callback.getParameters();
      const body = callback.getBody();
      if (parameters.length !== 1 || !/^\{\s*page\s*\}$/.test(parameters[0].getName()) || !Node.isBlock(body)) return { reason: 'Custom test fixtures are not supported by local conversion.' };
      title = testTitle; statements = body.getStatements();
    } else {
      if (testCount) return { reason: 'Additional statements outside the test are not supported by local conversion.' };
      statements.push(statement);
    }
  }
  const dirs = ctx.directories ?? defaultDirectories;
  const popup = popupNavigations(statements);
  const naming = hints ? alignTestSteps(hints, popup.statements.map(statement => {
    const expression = Node.isExpressionStatement(statement) ? statement.getExpression() : undefined;
    const call = expression && Node.isAwaitExpression(expression) ? expression.getExpression() : undefined;
    const access = call && Node.isCallExpression(call) ? call.getExpression() : undefined;
    if (!access || !Node.isPropertyAccessExpression(access)) return {};
    let target: Node = access.getExpression();
    if (Node.isCallExpression(target) && target.getExpression().getText() === 'expect' && target.getArguments().length === 1) target = target.getArguments()[0];
    return { action: access.getName(), label: locator(target)?.label };
  })) : undefined;
  const namingNotice = naming?.namingNotice;
  const sections = new Map<string, Section>();
  const sectionFor = (slug: string): Section => {
    const present = sections.get(slug);
    if (present) return present;
    const className = `${/^[0-9]/.test(slug) ? 'P' : ''}${pascal(slug)}Page`;
    const oldPage = ctx.existingPages.find(file => file.relativePath === `${dirs.pagesDir}/${slug}/${slug}.page.ts`);
    const oldClass = oldPage ? project.createSourceFile(`/method-names/${oldPage.relativePath}`, oldPage.content).getClasses()[0] : undefined;
    // Suffix grouped instances to avoid collisions with fixtures, JSON data and TS keywords.
    const instance = ctx.namingPlan?.steps.some(step => step.page) ? `${camel(slug)}Page` : camel(slug);
    const section: Section = { slug, className, instance, locators: new Map(), methods: new Map(),
      existingLocators: existingLocatorNames(project, ctx, `${dirs.pagesDir}/${slug}/${slug}.locators.ts`),
      methodIdentities: new Map(oldClass?.getMethods().map(method => [method.getName(), methodMeaning(method)]) ?? []) };
    sections.set(slug, section);
    return section;
  };
  let current: Section | undefined;
  const steps: string[] = [];
  const data: Record<string, string> = { title: hints?.title ?? title };
  const addData = (value: string, label: string): string => {
    const base = hints ? camel(label) : `value${Object.keys(data).length}`;
    let key = base, collision = 2;
    while (key in data) key = `${base}${collision++}`;
    data[key] = value; return `data.${key}`;
  };
  const addMethod = (section: Section, preferred: string, text: string): string => {
    if (!hints) { section.methods.set(preferred, text); return preferred; }
    const method = project.createSourceFile('/method-candidate.ts', `class Candidate { ${text} }`, { overwrite: true }).getClasses()[0].getMethods()[0];
    const meaning = methodMeaning(method);
    let name = [...section.methodIdentities].find(([, identity]) => identity === meaning)?.[0] ?? preferred;
    let collision = 2;
    while (section.methodIdentities.has(name) && section.methodIdentities.get(name) !== meaning) name = `${preferred}_${collision++}`;
    method.getNameNode().replaceWithText(name);
    section.methodIdentities.set(name, meaning); section.methods.set(name, method.getText()); return name;
  };
  const unsupported = (node?: Node, detail = 'This operation is not supported by local conversion rules.'): LocalResult => ({
    reason: `Local conversion stopped${node ? ` at line ${node.getStartLineNumber()}` : ''}: ${detail}`,
  });
  let stepIndex = 0;
  for (const statement of popup.statements) {
    if (!Node.isExpressionStatement(statement)) return unsupported(statement, `Statement type ${statement.getKindName()} needs interpretation.`);
    const awaited = statement.getExpression();
    if (!Node.isAwaitExpression(awaited)) return unsupported(statement, 'Expected an awaited Playwright action.');
    const call = awaited.getExpression();
    if (!Node.isCallExpression(call)) return unsupported(statement, 'Expected a Playwright method call.');
    const access = call.getExpression();
    if (!Node.isPropertyAccessExpression(access)) return unsupported(statement, 'Custom function calls need interpretation.');
    const action = access.getName();
    const receiver = access.getExpression();
    const args = call.getArguments();
    const hint = naming?.steps[stepIndex++];
    if (receiver.getText() === 'page' && action === 'goto') {
      const url = literal(args[0]);
      if (url === undefined || args.length !== 1) return unsupported(statement, 'page.goto requires one literal URL for local conversion.');
      let route: string;
      try { route = new URL(url, 'https://placeholder.invalid').pathname; } catch { return unsupported(statement, 'The navigation URL could not be parsed.'); }
      const routeSlug = route.replace(/^\/+|\/+$/g, '').replace(/[^a-zA-Z0-9]+/g, '-').toLowerCase() || 'home';
      const group = pageGroupSlug(hint?.page);
      const slug = group ?? routeSlug;
      namingActions.push({ action, label: routeSlug });
      const className = `${/^[0-9]/.test(slug) ? 'P' : ''}${pascal(slug)}Page`;
      if (!group && ctx.pageMap?.[route] && ctx.pageMap[route] !== className) return { reason: 'An established page mapping requires retrieval.' };
      current = sectionFor(slug);
      const waitsForPopup = popup.navigations.has(statement);
      const preferred = hints ? `open${pascal(hint?.label ?? slug)}${waitsForPopup ? 'AndWaitForPopup' : ''}` : waitsForPopup ? 'openAndWaitForPopup' : 'open';
      const method = addMethod(current, preferred, `async ${preferred}(url: string): Promise<void> {\n${waitsForPopup ? '    const popupPromise = this.page.waitForEvent("popup");\n' : ''}    await this.page.goto(url);\n${waitsForPopup ? '    await popupPromise;\n' : ''}  }`);
      steps.push(`await ${current.instance}.${method}(${addData(url, `${hint?.label ?? slug} Url`)});`);
      continue;
    }
    if (!current) current = sectionFor(pageGroupSlug(hint?.page) ?? 'continuation');
    let selected = locator(receiver);
    let assertion = false;
    if (Node.isCallExpression(receiver) && receiver.getExpression().getText() === 'expect' && receiver.getArguments().length === 1) {
      selected = locator(receiver.getArguments()[0]); assertion = true;
    }
    if (!selected || selected.type !== 'locator') {
      const factories = receiver.getDescendantsOfKind(SyntaxKind.PropertyAccessExpression).map(item => item.getName());
      return unsupported(statement, `Unsupported locator or locator options${factories.length ? ` (${[...new Set(factories)].join(', ')})` : ''}. Local rules require literal locator arguments and supported frame/locator chains.`);
    }
    const zeroArgs = assertion ? ['toBeVisible', 'toBeHidden', 'toBeChecked', 'toBeEnabled', 'toBeDisabled'] : ['click', 'check', 'uncheck'];
    const oneArg = assertion ? ['toHaveText', 'toContainText', 'toHaveValue'] : ['fill', 'press', 'selectOption'];
    let value: string | undefined;
    if (zeroArgs.includes(action)) { if (args.length) return unsupported(statement, `${action} options are not supported locally.`); }
    else if (oneArg.includes(action)) { value = literal(args[0]); if (value === undefined || args.length !== 1) return unsupported(statement, `${action} requires one literal string for local conversion.`); }
    else return unsupported(statement, `The ${action} operation is not supported locally.`);
    namingActions.push({ action, label: selected.label, target: selected.expression });
    const group = pageGroupSlug(hint?.page);
    if (group) current = sectionFor(group);
    const key = hash(selected.expression);
    const priorName = [...current.existingLocators].find(([, expression]) => expression === selected.expression)?.[0];
    const baseName = locatorFieldName(hint?.label ?? selected.label, hints && ['check', 'uncheck'].includes(action) ? 'Checkbox' : selected.suffix);
    let locatorName = priorName ?? baseName;
    let collision = 2;
    while (current.existingLocators.has(locatorName) && current.existingLocators.get(locatorName) !== selected.expression) locatorName = `${baseName}_${collision++}`;
    current.existingLocators.set(locatorName, selected.expression);
    current.locators.set(key, { name: locatorName, expression: selected.expression, css: selected.css, frame: selected.frame });
    const label = hint?.label ?? selected.label;
    const preferred = hints ? `${assertion ? 'verify' : action === 'fill' ? 'enter' : action}${pascal(label).slice(0, 60) || 'Element'}` : `${action}${pascal(selected.label).slice(0, 45) || 'Element'}_${key}`;
    const expression = `this.locators.${locatorName}`;
    const method = addMethod(current, preferred, `async ${preferred}(${value === undefined ? '' : 'value: string'}): Promise<void> {\n    await ${assertion ? `expect(${expression})` : expression}.${action}(${value === undefined ? '' : 'value'});\n  }`);
    steps.push(`await ${current.instance}.${method}(${value === undefined ? '' : addData(value, `${assertion ? 'expected ' : ''}${label}`)});`);
  }
  if (!steps.length) return unsupported();
  const files: GeneratedFile[] = [];
  const basePath = `${dirs.pagesDir}/base.page.ts`;
  const existingBase = ctx.existingPages.find(file => /class\s+BasePage\b/.test(file.content));
  if (existingBase && (existingBase.relativePath !== basePath || existingBase.content !== baseSource)) return { reason: 'The existing BasePage has a custom interface.' };
  files.push({ path: basePath, mode: 'create', content: baseSource });
  const flowName = hints?.title?.replace(/[^a-zA-Z0-9]+/g, '-').replace(/^-+|-+$/g, '').toLowerCase().slice(0, 60).replace(/-+$/, '') || 'flow';
  const flow = `${flowName}-${hash(codegenSource + (hints ? `\nTEST STEPS:\n${ctx.testSteps}` : '') + (ctx.namingPlan ? JSON.stringify(ctx.namingPlan) : ''))}`;
  const testPath = ctx.continuationSpec || `${dirs.testsDir}/${flow}/${flow}.spec.ts`;
  const dataPath = `${dirs.testDataDir}/${flow}/${flow}.data.json`;
  const imports = ["import { test } from '@playwright/test';"];
  const instances: string[] = [];
  for (const section of sections.values()) {
    const pagePath = `${dirs.pagesDir}/${section.slug}/${section.slug}.page.ts`;
    const locatorsPath = `${dirs.pagesDir}/${section.slug}/${section.slug}.locators.ts`;
    const locatorsName = section.className.replace(/Page$/, 'Locators');
    const locatorItems = [...section.locators.values()];
    // Only factor a frame scope when it is shared. One-off frame fields add noise
    // without reducing duplication.
    const frameCounts = new Map<string, number>();
    for (const item of locatorItems) if (item.frame) frameCounts.set(item.frame, (frameCounts.get(item.frame) ?? 0) + 1);
    const frameFields = new Map<string, string>();
    const usedNames = new Set(section.existingLocators.keys());
    for (const [frame, count] of frameCounts) {
      if (count < 2) continue;
      const existing = [...section.existingLocators].find(([, expression]) => expression === frame)?.[0];
      let name = existing ?? `FRAME_${hash(frame).toUpperCase()}`;
      let collision = 2;
      while (usedNames.has(name) && section.existingLocators.get(name) !== frame) name = `FRAME_${hash(frame).toUpperCase()}_${collision++}`;
      usedNames.add(name); frameFields.set(frame, name);
    }
    const sharedFrames = [...frameFields].map(([frame, name]) => `${frame.includes('.locator(') ? '// Recorded CSS/XPath retained. Prefer stable test IDs or role locators where available; verify before changing.\n  ' : ''}readonly ${name}: FrameLocator = ${frame.replace(/^page\./, 'this.page.')};`);
    const fields = locatorItems.map(item => {
      const frame = item.frame && frameFields.get(item.frame);
      const expression = frame ? `this.${frame}${item.expression.slice(item.frame!.length)}` : item.expression.replace(/^page\./, 'this.page.');
      return `${item.css && !frame ? '// Recorded CSS/XPath retained. Prefer stable test IDs or role locators where available; verify before changing.\n  ' : ''}readonly ${item.name}: Locator = ${expression};`;
    });
    const locatorDeclarations = [...sharedFrames, ...fields].join('\n\n  ');
    const locatorMembers = `constructor(private page: Page) {}\n\n  ${locatorDeclarations}`;
    const locatorImports = sharedFrames.length ? 'FrameLocator, Locator, Page' : 'Locator, Page';
    const methods = [...section.methods.values()].join('\n\n  ');
    const pageMembers = `private readonly locators: ${locatorsName};\n\n  constructor(page: Page) {\n    super(page);\n    this.locators = new ${locatorsName}(page);\n  }\n\n  ${methods}`;
    const candidates = [
      { path: locatorsPath, members: locatorMembers, content: `${marker}\nimport { ${locatorImports} } from '@playwright/test';\n\nexport class ${locatorsName} {\n  ${locatorMembers}\n}\n` },
      { path: pagePath, members: methods, content: `${marker}\nimport { expect, type Page } from '@playwright/test';\nimport { BasePage } from ${JSON.stringify(importPath(pagePath, basePath))};\nimport { ${locatorsName} } from ${JSON.stringify(importPath(pagePath, locatorsPath))};\n\nexport class ${section.className} extends BasePage {\n  ${pageMembers}\n}\n` },
    ];
    for (const candidate of candidates) {
      const existing = ctx.existingPages.find(file => file.relativePath === candidate.path);
      if (existing) {
        if (!existing.content.startsWith(marker)) return { reason: 'Existing page objects require repository-aware reuse.' };
        // Refuse to reuse a locally generated method whose body has since been edited.
        const before = project.createSourceFile(`/existing/${candidate.path}`, existing.content).getClasses()[0];
        const after = project.createSourceFile(`/desired/${candidate.path}`, candidate.content).getClasses()[0];
        if (before?.getName() !== after.getName()) return unsupported();
        for (const method of after.getMethods()) {
          const prior = before.getMethod(method.getName());
          if (prior && !sameCode(prior, method)) return { reason: 'An existing action method was customized.' };
        }
        // A modified constructor or locator can change semantics even while types still pass.
        if (candidate.path === locatorsPath) {
          const body = before.getConstructors()[0]?.getBodyText() ?? '';
          const existingNames = existingLocatorNames(project, ctx, candidate.path);
          for (const item of section.locators.values()) {
            const property = before.getProperty(item.name);
            const initializer = property?.getInitializer();
            if (property && (initializer ? existingNames.get(item.name) !== item.expression : !body.includes(`this.${item.name} = ${item.expression};`))) return { reason: 'An existing locator was customized.' };
          }
        } else if (!sameCode(before.getConstructors()[0], after.getConstructors()[0])) return { reason: 'An existing page constructor was customized.' };
      }
      files.push({ path: candidate.path, mode: existing ? 'merge' : 'create', content: existing ? candidate.members : candidate.content });
    }
    imports.push(`import { ${section.className} } from ${JSON.stringify(importPath(testPath, pagePath))};`);
    instances.push(`const ${section.instance} = new ${section.className}(page);`);
  }
  imports.push(`const data: ${JSON.stringify(Object.fromEntries(Object.keys(data).map(key => [key, '__STRING__']))).replace(/"__STRING__"/g, 'string')} = require(${JSON.stringify(importPath(testPath, dataPath))});`);
  files.push({ path: dataPath, mode: 'create', content: JSON.stringify(data, null, 2) + '\n' });
  const dataDeclaration = imports.pop()!;
  const body = [...instances, ...steps].join('\n  ');
  if (ctx.continuationSpec) {
    const continuationMarker = `// POM Agent continuation ${hash(codegenSource)}`;
    const continuationData = dataDeclaration.replace(/\bdata\b/g, 'continuationData');
    const continuationBody = body.replace(/\bdata\./g, 'continuationData.');
    files.push({ path: testPath, mode: 'append-test', content: `${marker}\n${imports.filter(item => item !== "import { test } from '@playwright/test';").join('\n')}\n\nasync ({ page }) => {\n  ${continuationMarker}\n  ${continuationData}\n  ${continuationBody}\n};\n` });
  } else files.push({ path: testPath, mode: 'create', content: `${marker}\n${[...imports, dataDeclaration].join('\n')}\n\ntest(data.title, async ({ page }) => {\n  ${body}\n});\n` });
  return { result: { files, summary: `${ctx.continuationSpec ? 'Extended the selected test with' : 'Converted'} ${sections.size} page(s) using ${ctx.namingPlan ? 'Copilot organization and local code generation' : `local rules${hints ? ' and local naming guidance' : ''}`}.` }, reason: 'All statements are supported by local rules.', namingNotice, namingActions };
}
