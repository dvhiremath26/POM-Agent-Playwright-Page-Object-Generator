import { test, TestContext } from 'node:test';
import assert from 'node:assert/strict';
import * as fs from 'node:fs/promises';
import * as os from 'node:os';
import * as path from 'node:path';
import { generateLocally } from '../dist/localGenerator';
import { buildRepoContext } from '../dist/indexer';
import { writeGeneratedFiles } from '../dist/writer';
import { checkLocatorCompatibility } from '../dist/locatorCompatibility';
import { executeAgent } from '../dist/agent';

const recording = `await page.goto('/login');
await page.getByRole('textbox', { name: 'Login' }).fill('sample-user');
await page.getByRole('textbox', { name: 'Password' }).fill('sample-password');
await page.getByRole('button', { name: 'Login' }).click();`;
const empty = { existingPages: [], conventions: null };
async function fixture(t: TestContext): Promise<string> {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'pom-locator-style-'));
  t.after(() => fs.rm(root, { recursive: true, force: true })); return root;
}

test('new locator classes match the requested uppercase inline initializer format', () => {
  const result = generateLocally(recording, empty).result!;
  const locators = result.files.find(file => file.path.endsWith('.locators.ts'))!.content;
  assert.match(locators, /import \{ Locator, Page \} from '@playwright\/test';/);
  assert.match(locators, /constructor\(private page: Page\) \{\}/);
  assert.match(locators, /readonly USERNAME_FIELD: Locator = this\.page\.getByRole\("textbox", \{"name":"Login"\}\);/);
  assert.match(locators, /readonly PASSWORD_FIELD: Locator = this\.page/);
  assert.match(locators, /readonly LOGIN_BUTTON: Locator = this\.page/);
  assert.doesNotMatch(locators, /this\.USERNAME_FIELD\s*=/);
  assert.match(result.files.find(file => file.path.endsWith('login.page.ts'))!.content, /this\.locators\.USERNAME_FIELD/);
});

test('duplicate labels remain distinct and stable when later recordings reuse only one', async t => {
  const root = await fixture(t);
  const source = `await page.goto('/login');
await page.frameLocator('#first').getByRole('button', { name: 'Login' }).click();
await page.frameLocator('#second').getByRole('button', { name: 'Login' }).click();`;
  const first = generateLocally(source, empty).result!;
  await writeGeneratedFiles(root, first.files);
  const ctx = await buildRepoContext(root, 'pages', 'conventions.md');
  const second = generateLocally(`await page.goto('/login');\nawait page.frameLocator('#second').getByRole('button', { name: 'Login' }).click();`, ctx).result!;
  assert.ok(second);
  const locators = second.files.find(file => file.path.endsWith('.locators.ts'))!.content;
  assert.match(locators, /readonly LOGIN_BUTTON_2: Locator/);
  assert.doesNotMatch(locators, /readonly LOGIN_BUTTON: Locator/);
  const written = await writeGeneratedFiles(root, second.files);
  assert.ok(written.every(file => !file.endsWith('.locators.ts') && !file.endsWith('.page.ts')));
});

test('legacy locator names and methods survive while new fields use the requested style', async t => {
  const root = await fixture(t);
  await fs.mkdir(path.join(root, 'pages/login'), { recursive: true });
  const legacy = `// Generated by POM Agent local rules v1.
import type { Page, Locator } from '@playwright/test';
export class LoginLocators {
  readonly legacyLoginInput: Locator;
  constructor(page: Page) { this.legacyLoginInput = page.getByRole("textbox", {"name":"Login"}); }
}`;
  await fs.writeFile(path.join(root, 'pages/login/login.locators.ts'), legacy);
  const ctx = await buildRepoContext(root, 'pages', 'conventions.md');
  const generated = generateLocally(recording, ctx).result!;
  assert.ok(generated);
  await writeGeneratedFiles(root, generated.files);
  const merged = await fs.readFile(path.join(root, 'pages/login/login.locators.ts'), 'utf8');
  assert.match(merged, /readonly legacyLoginInput: Locator;/);
  assert.match(merged, /constructor\(private page: Page\)/);
  assert.match(merged, /readonly PASSWORD_FIELD: Locator = this.page/);
  assert.match(generated.files.find(file => file.path.endsWith('login.page.ts'))!.content, /this.locators.legacyLoginInput/);
  const again = generateLocally(recording, await buildRepoContext(root, 'pages', 'conventions.md')).result!;
  assert.ok(again);
  assert.deepEqual(await writeGeneratedFiles(root, again.files), []);
});

test('older compact page methods remain reusable but changes to their behavior are rejected', async t => {
  const root = await fixture(t);
  const generated = generateLocally(recording, empty).result!;
  const page = generated.files.find(file => file.path.endsWith('login.page.ts'))!;
  // Match the layout emitted by earlier releases without changing syntax or values.
  page.content = page.content.replace(/\{\n    ([\s\S]*?)\n  \}/g, (_match, body: string) => `{ ${body.replace(/\n    /g, ' ')} }`);
  await writeGeneratedFiles(root, generated.files);
  const extended = `${recording}\nawait page.getByRole('link', { name: 'Settings' }).click();`;
  const result = generateLocally(extended, await buildRepoContext(root, 'pages', 'conventions.md'));
  assert.ok(result.result, result.reason);
  await writeGeneratedFiles(root, result.result.files);
  const merged = await fs.readFile(path.join(root, page.path), 'utf8');
  assert.match(merged, /\n  async clickSettings_\w+\(\): Promise<void> \{\n    await this.locators.SETTINGS_LINK.click\(\);\n  \}/);
  const again = generateLocally(extended, await buildRepoContext(root, 'pages', 'conventions.md'));
  assert.ok(again.result, again.reason);
  assert.deepEqual(await writeGeneratedFiles(root, again.result.files), []);
  await fs.writeFile(path.join(root, page.path), merged.replace('this.page.goto(url)', 'this.page.reload()'));
  const changed = generateLocally(extended, await buildRepoContext(root, 'pages', 'conventions.md'));
  assert.equal(changed.result, undefined);
  assert.match(changed.reason, /customized/);
});

test('incompatible class-field configuration stops before generation', async t => {
  const root = await fixture(t);
  await fs.writeFile(path.join(root, 'base.json'), JSON.stringify({ compilerOptions: { target: 'ES2022' } }));
  await fs.writeFile(path.join(root, 'tsconfig.json'), JSON.stringify({ extends: './base.json' }));
  assert.throws(() => checkLocatorCompatibility(root), /useDefineForClassFields/);
  let calls = 0;
  await assert.rejects(executeAgent({ workspaceRoot: root, codegenSource: recording, conventionsFile: 'conventions.md' }, {
    local: () => { calls++; throw new Error('Must not generate'); }, validate: async () => ({ ok: true, errors: '' }),
  }), /useDefineForClassFields/);
  assert.equal(calls, 0);
  await fs.writeFile(path.join(root, 'tsconfig.json'), JSON.stringify({ extends: './base.json', compilerOptions: { useDefineForClassFields: false } }));
  assert.doesNotThrow(() => checkLocatorCompatibility(root));
  for (const module of ['Node16', 'Node18', 'Node20', 'NodeNext']) {
    await fs.writeFile(path.join(root, 'tsconfig.json'), JSON.stringify({ compilerOptions: { module } }));
    assert.throws(() => checkLocatorCompatibility(root), /useDefineForClassFields/, module);
  }
});
